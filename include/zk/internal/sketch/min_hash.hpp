    template<std::unsigned_integral Item>
    void update(Item const& x) {
        for(size_t i = 0; i < num_hashes_; i++) {
            sig_[i] = std::min(sig_[i], hash(i, x));
        }
    }

    void merge(MinHashSignature const& other) {
        for(size_t i = 0; i < num_hashes_; i++) {
            sig_[i] = std::min(sig_[i], other.sig_[i]);
        }
    }

    double similarity(MinHashSignature const& other) const {
        size_t eq = 0;
        for(size_t i = 0; i < num_hashes_; i++) {
            eq += (sig_[i] == other.sig_[i]);
        }
        return double(eq) / double(2 * num_hashes_ - eq);
    }
